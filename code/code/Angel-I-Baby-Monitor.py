# Import required packages
import cv2
import matplotlib.pyplot as plt
from keras.models import Sequential
from keras.layers import Conv2D, MaxPooling2D, Dense, Dropout, Flatten
from keras.optimizers import Adam
from keras.preprocessing.image import ImageDataGenerator

# Initialize image data generator with rescaling
train_data_gen = ImageDataGenerator(rescale=1./255) #preprocess all images inside the train dataset
validation_data_gen = ImageDataGenerator(rescale=1./255) #preprocess all images inside the validation dataset

# Preprocess all train images
train_generator = train_data_gen.flow_from_directory(
        '/content/drive/MyDrive/ColabNotebooks/dataset1/train',
        target_size=(48, 48),
        batch_size=64,
        color_mode="grayscale", #1 color channel
        class_mode='categorical')

# Preprocess all validation images
validation_generator = validation_data_gen.flow_from_directory(
        '/content/drive/MyDrive/ColabNotebooks/data/validation',
        target_size=(48, 48),
        batch_size=64,
        color_mode="grayscale",
        class_mode='categorical')

# Create CNN model
emotion_model = Sequential()

# Add convolutional layers with increasing filters and kernel sizes
emotion_model.add(Conv2D(32, kernel_size=(3, 3), activation='relu', input_shape=(48, 48, 1)))
emotion_model.add(Conv2D(64, kernel_size=(3, 3), activation='relu'))
emotion_model.add(MaxPooling2D(pool_size=(2, 2)))
emotion_model.add(Dropout(0.25))

emotion_model.add(Conv2D(128, kernel_size=(3, 3), activation='relu'))
emotion_model.add(MaxPooling2D(pool_size=(2, 2)))
emotion_model.add(Conv2D(256, kernel_size=(3, 3), activation='relu'))
emotion_model.add(MaxPooling2D(pool_size=(2, 2)))
emotion_model.add(Dropout(0.25))

emotion_model.add(Conv2D(512, kernel_size=(3, 3), activation='relu'))
emotion_model.add(MaxPooling2D(pool_size=(2, 2)))
emotion_model.add(Dropout(0.25))

# Flatten the output from the convolutional layers
emotion_model.add(Flatten())

# Add dense layers with dropout regularization
emotion_model.add(Dense(512, activation='relu'))
emotion_model.add(Dropout(0.5))
emotion_model.add(Dense(256, activation='relu'))
emotion_model.add(Dropout(0.5))
emotion_model.add(Dense(128, activation='relu'))
emotion_model.add(Dropout(0.5))
emotion_model.add(Dense(64, activation='relu'))
emotion_model.add(Dropout(0.5))

# Add the output layer with softmax activation for multiclass classification
emotion_model.add(Dense(7, activation='softmax'))

cv2.ocl.setUseOpenCL(False)

# Compile the model with categorical crossentropy loss and Adam optimizer
emotion_model.compile(loss='categorical_crossentropy', optimizer=Adam(lr=0.0001, decay=1e-6), metrics=['accuracy'])

# Train the model using the data generator with 50 epochs
history = emotion_model.fit_generator(train_generator,steps_per_epoch=train_generator.samples // train_generator.batch_size,epochs=50, validation_data=validation_generator, validation_steps=validation_generator.samples // validation_generator.batch_size)


# Plot the accuracy and loss
plt.plot(history.history['accuracy'])
plt.plot(history.history['val_accuracy'])
plt.title('Model Accuracy')
plt.ylabel('Accuracy')
plt.xlabel('Epoch')
plt.legend(['train', 'validation'], loc='upper left')
plt.show()

plt.plot(history.history['loss'])
plt.plot(history.history['val_loss'])
plt.title('Model Loss')
plt.ylabel('Loss')
plt.xlabel('Epoch')
plt.legend(['train', 'validation'], loc='upper left')
plt.show()

# save model structure in jason file
model_json = emotion_model.to_json()
with open("/content/drive/MyDrive/ColabNotebooks/model/emotion_model_latest.json", "w") as json_file:
    json_file.write(model_json)

# save trained model weight in .h5 file
